# Conventional Commit message examples.
# Format: <type>: <description>

# feat: a new feature
git commit -m "feat: add hello-node script"

# chore: maintenance tasks
git commit -m "chore: add .gitignore and .env.example"

# docs: documentation changes
git commit -m "docs: update README with setup instructions"

# fix: bug fixes
git commit -m "fix: correct typo in hello-node output"

# refactor: code changes that neither fix a bug nor add a feature
git commit -m "refactor: extract greeting to a constant"

# test: adding or updating tests
git commit -m "test: add hello-node smoke test"
